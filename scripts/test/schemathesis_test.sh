#!/usr/bin/env bash
# The very first line tells the computer to run this file with the Bash shell.

# /**
#  * @file schemathesis_test.sh
#  * @brief Fuzz the OpenAPI-documented API with Schemathesis using a fresh bearer token.
#  * @details This script fuzzes the documented API using Schemathesis and a fresh bearer token.
#  * It creates a throwaway provider, logs in to get a real token, then runs the fuzzer against the OpenAPI spec.
#  * It reports contract violations and exits with the fuzzer's own status.
#  *
#  * WHY THIS FILE MATTERS IN THE SERVER:
#  * This is the spec-driven API contract check run after API changes.
#  * A developer or CI runs it against a local server that has the OpenAPI spec generated.
#  * Without it changes that break the documented request or response shape would go unnoticed.
#  *
#  * CONCEPTS TO LEARN (for beginners):
#  * - OpenAPI specification: https://spec.openapis.org/oas/latest.html
#  * - Schemathesis: https://github.com/schemathesis/schemathesis
#  * - Hypothesis (the test generator): https://hypothesis.readthedocs.io/
#  *
#  * @author Amr Osman <dr3mro@gmail.com>
#  * @date 2026-11-16
#  */
# Spec-driven, stateful-ish API fuzzing for Valhalla-server using Schemathesis (the lightweight,
# pip-installable alternative to RESTler - no .NET SDK, no compiler step). It reads docs/openapi.json
# directly (regenerated by `cmake --build` / tools/docs/build.sh) and uses Hypothesis to generate
# boundary-value, malformed, and negative test cases per endpoint, then checks responses for server
# errors, schema violations, and other API-contract breaks.
#
# 1. Logs in as a throwaway provider account (created fresh for this run) to get a real JWT, since the
#    spec marks every operation as needing bearerAuth - without a token almost everything just 401s
#    and Schemathesis never gets past the auth wall.
# 2. Runs `st run docs/openapi.json` against the live server with that token on every request.
#
# Usage: ./schemathesis_test.sh
# Env:   BASE_URL      (default http://127.0.0.1:8080/api/v2)
#        SPEC          (default docs/openapi.json, next to this script)
#        OUT_DIR       (default schemathesis-results, next to this script)
#        MAX_EXAMPLES  (default 50)   - test cases generated per endpoint
#        MAX_TIME      (default 300)  - overall time budget in seconds
#        CHECKS        (default all) - comma list, see `st run --help`
#        EXTRA_ARGS    - extra args appended to the `st run` invocation
# Needs: python3, pip-installed `schemathesis` (this script installs it into
#        ~/.local if the `st` command isn't already on PATH).
# No `-e`: the fuzzer's status is captured explicitly after the subshell and propagated at the end.
set -uo pipefail  # Treat unset variables and failed pipeline steps as errors.

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"  # Absolute repository root, found from this file's own location.
# Every knob is env-overridable; defaults target the local server and keep generated files under build/testing.
BASE_URL="${BASE_URL:-http://127.0.0.1:8080/api/v2}"  # Server address to fuzz; defaults to a local server.
SPEC="${SPEC:-$ROOT/docs/openapi.json}"  # Path to the OpenAPI specification the fuzzer reads.
OUT_DIR="${OUT_DIR:-$ROOT/build/testing/schemathesis-results}"  # Folder for reports and generated files, kept out of the source tree.
MAX_EXAMPLES="${MAX_EXAMPLES:-50}"  # How many test cases to generate for each endpoint.
MAX_TIME="${MAX_TIME:-300}"  # Overall time budget for the fuzzer, in seconds.
CHECKS="${CHECKS:-all}"  # Which contract checks to run; all by default.
# positive_data_acceptance (ST202 "Schema-valid request rejected") assumes a request that matches
# the OpenAPI schema should always be accepted. That holds for pure data-shape validation, but this
# API has business rules no JSON Schema can express - "Delete is NOT implemented for entity type
# ...", "Initial service admin_id and owner_id should be equal to that of provider_id", SQL
# injection pattern detection, and the like - which schemathesis's fuzzer will always eventually
# trip and flag as a false positive. Excluded by default; run with EXCLUDE_CHECKS= (empty) to see them again.
EXCLUDE_CHECKS="${EXCLUDE_CHECKS-positive_data_acceptance}"  # One noisy check is off by default because this API has business rules a schema cannot express.
EXTRA_ARGS="${EXTRA_ARGS:-}"  # Extra words appended to the fuzzer command line.
# Logout (/clients/{type}/logout) really does kill the session server-side (GateKeeper::logout ->
# SessionManager::removeSession). We log in ONCE and hand Schemathesis that single token for every
# generated test case; if the fuzzer happens to hit logout, every later test case in the run reuses
# the now-dead token and 401s - a cascade of "failures" that are a test-harness artifact, not real
# bugs. Exclude logout from fuzzing (it would need a fresh token per case to be tested meaningfully).
EXCLUDE_PATH_REGEX="${EXCLUDE_PATH_REGEX:-/logout$}"  # Skip logout: it kills the single shared token and would break all later cases.

# Prefer a user-local `st` install; the private venv created below is a fallback.
export PATH="$HOME/.local/bin:$PATH"  # Look for a user-installed fuzzer first.
# Keep Hypothesis's example database in build/testing so fuzzing never writes into the source tree.
export HYPOTHESIS_STORAGE_DIRECTORY="${HYPOTHESIS_STORAGE_DIRECTORY:-$ROOT/build/testing/.hypothesis}"  # Keep the generator's example database under build/testing.
mkdir -p "$HYPOTHESIS_STORAGE_DIRECTORY"  # Make sure that storage folder exists.

# Colour only on a terminal; logs and CI output stay plain text.
if [[ -t 1 ]]; then G=$'\033[32m'; R=$'\033[31m'; Y=$'\033[33m'; B=$'\033[1m'; N=$'\033[0m'; else G=""; R=""; Y=""; B=""; N=""; fi
# @brief Print a plain line.
# @param $* Text to print.
say()  { printf '%s\n' "$*"; }
# @brief Print a yellow [*] informational line.
# @param $* Text to print.
note() { printf '%s[*]%s %s\n' "$Y" "$N" "$*"; }
# @brief Print a green [+] success line.
# @param $* Text to print.
ok()   { printf '%s[+]%s %s\n' "$G" "$N" "$*"; }
# @brief Print a red [-] error line to stderr.
# @param $* Text to print.
err()  { printf '%s[-]%s %s\n' "$R" "$N" "$*" >&2; }

command -v python3 >/dev/null || { err "python3 is required but was not found on PATH"; exit 2; }  # Stop with a clear message if Python is missing.
[[ -f $SPEC ]] || { err "OpenAPI spec not found: $SPEC (run 'cmake --build' or tools/docs/build.sh to generate it)"; exit 2; }  # Stop if the spec has not been generated yet.

# Install into a private venv rather than system Python so the fuzzer never needs global privileges.
if ! command -v st >/dev/null; then  # Install the fuzzer into a private folder if it is not available.
	note "schemathesis ('st') not found - creating a virtualenv ..."
	VENV_DIR="${VENV_DIR:-$HOME/.cache/valhalla-schemathesis-venv}"  # Where the private Python environment will live.
	python3 -m venv "$VENV_DIR" || { err "python3 -m venv failed"; exit 2; }  # Create that private Python environment.
	"$VENV_DIR/bin/pip" install --quiet schemathesis || { err "pip install schemathesis failed"; exit 2; }  # Install the fuzzer into the private environment, not system-wide.
	export PATH="$VENV_DIR/bin:$PATH"  # Put the newly installed fuzzer on the command search path.
	command -v st >/dev/null || { err "schemathesis installed but 'st' still not on PATH"; exit 2; }
fi

note "Base URL: $BASE_URL"
note "Spec:     $SPEC"
note "Results:  $OUT_DIR"
mkdir -p "$OUT_DIR"  # Make sure the results folder exists.

# ---------------------------------------------------------------------------
# 1. Create a throwaway provider and log in to get a real JWT for every request.
# ---------------------------------------------------------------------------
# Unique per-run username keeps the throwaway account from colliding with earlier runs.
RUN="$$_$RANDOM"  # A unique run id so the throwaway username never collides.
say "${B}== Creating throwaway provider (run $RUN) and logging in ==${N}"
CREATE_BODY=$(cat <<JSON
{"avatar":"http://www.gravatar.com/avatar/205e460b479e2e5b48aec07710c08d50?s=200","active":true,"language":"en","username":"fuzzprov$RUN","password":"1234@Abc!","fullname":"Fuzz Test","phone":"+201299999999","email":"fuzzprov$RUN@mail.com","country":"Egypt","city":"Damietta","address":"portsaid street","dob":"17-02-1985","gender":"Male","position":"Doctor","speciality":"Cardiology"}
JSON
)
CREATE_STATUS=$(curl -s -o /dev/null -w '%{http_code}' -X POST "$BASE_URL/clients/providers/create" \
	-H 'Content-Type: application/json' -d "$CREATE_BODY")
CREATE_STATUS="${CREATE_STATUS:-000}"  # Treat a missing status as 000 (no response).
if [[ $CREATE_STATUS != 200 && $CREATE_STATUS != 201 ]]; then  # The account must be created (or already exist) before we can log in.
	err "Could not create the throwaway account (HTTP $CREATE_STATUS). Is the server running at $BASE_URL ?"
	err "  check with: curl $BASE_URL/hello"
	exit 2
fi

# The password is a fixed fixture for the throwaway account created above, not a real credential.
LOGIN_BODY=$(printf '{"username":"fuzzprov%s","password":"1234@Abc!"}' "$RUN")  # Build the login JSON with the fixture password and unique username.
LOGIN_RESPONSE=$(curl -s -X POST "$BASE_URL/clients/providers/login" -H 'Content-Type: application/json' -d "$LOGIN_BODY")  # Log in to obtain a real token for the fuzzer.
# Accept either token field name since both have been used by the API; an empty result is a setup failure.
TOKEN=$(python3 -c "import json,sys; print(json.loads(sys.argv[1]).get('access_token') or json.loads(sys.argv[1]).get('token') or '')" "$LOGIN_RESPONSE" 2>/dev/null)
if [[ -z $TOKEN ]]; then  # No token means the setup failed, so stop.
	err "Login did not return a token. Raw response: $LOGIN_RESPONSE"
	exit 2
fi
ok "Got a token for throwaway provider fuzzprov$RUN"
echo

# ---------------------------------------------------------------------------
# 2. Run Schemathesis against the live server with that token on every request.
# ---------------------------------------------------------------------------
say "${B}== Running Schemathesis (max-examples=$MAX_EXAMPLES, max-time=${MAX_TIME}s, checks=$CHECKS) ==${N}"
# shellcheck disable=SC2086
# Run from OUT_DIR so Hypothesis/Schemathesis caches land there, not the repo root.
# The opening parenthesis starts a subshell: a child shell whose folder changes stay local to the block below.

(
  cd "$OUT_DIR" || exit 1  # Run the fuzzer from the results folder so caches land there.
  st run "$SPEC" \
	--url "$BASE_URL" \
	-H "Authorization: Bearer $TOKEN" \
	--checks="$CHECKS" \
	${EXCLUDE_CHECKS:+--exclude-checks="$EXCLUDE_CHECKS"} \
	--max-examples="$MAX_EXAMPLES" \
	--max-time="$MAX_TIME" \
	--exclude-path-regex "$EXCLUDE_PATH_REGEX" \
	--report=junit \
	--report-dir="$OUT_DIR" \
	$EXTRA_ARGS
)
# Capture the fuzzer's exit code before any other command can overwrite $?.
STATUS=$?  # Save the fuzzer's result before any other command can overwrite it.

echo
say "Report dir: $OUT_DIR"
note "Note: endpoints that depend on ids created by OTHER endpoints (read/update/delete by id) will mostly"
note "get 404s here, since Schemathesis fuzzes each operation independently rather than chaining create ->"
note "use-the-id -> delete like sqlmap_test.sh's generator does. That's expected, not a bug."
note "Note: /logout endpoints are excluded from fuzzing - they invalidate the one shared token for the"
note "rest of the run, which would otherwise cause a cascade of unrelated 401 \"failures\"."

# Propagate schemathesis's own status so CI fails when the fuzzer found contract violations.
if ((STATUS != 0)); then  # Report and propagate a failing fuzz run to the caller.
	err "Schemathesis reported failures - see the output above and $OUT_DIR for the JUnit report."
	exit "$STATUS"  # Return exactly the fuzzer's exit code so CI sees the failure.
fi
ok "No failures reported."
exit 0
