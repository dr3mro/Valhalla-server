/**
 * @file passwordcrypt.hpp
 * @brief A small wrapper around libsodium's password-hashing functions.
 *        (Originally: "Thin wrapper around libsodium's password-hashing
 * primitives used by the password workers.")
 * @details This header declares a class that turns a plain-text password into a
 *          stored hash, and that checks a plain-text password against a stored
 *          hash. New hashes use the Argon2id recipe, but older scrypt hashes
 * are still understood so existing accounts keep working. The class holds
 *          almost no data of its own; its main job is to make sure libsodium is
 *          ready before any hashing happens.
 *
 * WHY THIS FILE MATTERS IN THE SERVER:
 * Checking passwords is the first line of defence for every login. The session
 * manager calls PasswordCrypt (through PasswordWorker) to verify passwords off
 * the web request threads. Without this file there would be no safe way to
 * store or check passwords, so nobody could log in to Valhalla.
 *
 * CONCEPTS TO LEARN (for beginners):
 * - Password hashing (Argon2/scrypt):
 * https://doc.libsodium.org/password_hashing/
 * - OWASP password storage advice:
 * https://cheatsheetseries.owasp.org/cheatsheets/Password_Storage_Cheat_Sheet.html
 * - std::optional (a value that may be missing):
 * https://en.cppreference.com/w/cpp/utility/optional
 * - Threads and concurrency in C++: https://en.cppreference.com/w/cpp/thread
 *
 * @author Amr Osman <dr3mro@gmail.com>
 * @date 2026-11-16
 */

#pragma once  // Include this header at most once per source file.
// std::optional: a container that may or may not hold a value (used when
// hashing can fail).
#include <optional>
// std::string: used for the password and for the encoded hash.
#include <string>

/**
 * @class PasswordCrypt
 * @brief Thin wrapper around libsodium's password-hashing primitives used by
 * the password workers.
 * @details Owns no per-instance state beyond ensuring libsodium is initialized
 * in the constructor. Hashing uses Argon2id at OWASP's minimum recommended
 * cost; verification also accepts hashes produced by the legacy scrypt scheme
 * so existing accounts remain valid. The stored hash is self-describing
 * (algorithm, cost, salt and digest), which is how verifyPassword selects the
 * algorithm without any extra metadata.
 *
 * In everyday words: a "hash" is a one-way, deliberately slow, scrambled
 * version of a password. We store the hash and never the real password.
 * "Argon2id" and "scrypt" are the names of the recipes used to scramble it.
 * "Self-describing" means the hash string itself records the recipe and the
 * amount of work used, so verification needs no separate note. A "salt" is
 * random data mixed in so two people with the same password still get different
 * hashes.
 * @warning The hashes are intentionally expensive; callers must run
 * hashPassword()/verifyPassword() on a PasswordWorker, never on a Drogon IO
 * thread. See runOnPasswordWorker().
 */
class PasswordCrypt
{
 public:
  /**
   * @brief Initializes libsodium, reporting a critical error
   * (Message::CriticalMessage) on failure.
   * @details libsodium is a library that must be set up once before any of
   * its functions are used; this constructor does that setup. If setup fails,
   * a critical error is logged but the object is still created, so later
   * password operations will simply fail.
   */
  PasswordCrypt();  // Sets up libsodium so the hashing functions are safe to
                    // call.
  PasswordCrypt(const PasswordCrypt&) =
      default;  // Copying is fine; there is no owned resource to duplicate.
  PasswordCrypt(
      PasswordCrypt&&) = default;  // Moving is fine for the same reason.
  PasswordCrypt& operator=(const PasswordCrypt&) =
      default;  // Copy assignment is fine; no per-instance state to manage.
  PasswordCrypt& operator=(PasswordCrypt&&) =
      default;  // Move assignment is fine for the same reason.
  virtual ~PasswordCrypt() = default;  // Virtual destructor allows safe use
                                       // through a base-class pointer.

  /**
   * @brief Produces a self-describing Argon2id hash string for @p password.
   * @details Uses a random salt generated by libsodium. The cost parameters
   * are deliberately low enough for the dedicated worker pool but meet
   * OWASP's minimum recommendations. In everyday words: we make a random
   * salt, mix it with the password using the Argon2id recipe, and return one
   * string holding the recipe settings, the salt and the result. "nullopt"
   * means "no value" and is returned when the machine cannot spare the needed
   * memory.
   * @param[in] password Plaintext password to hash.
   * @return The encoded hash string on success, or `std::nullopt` if
   * libsodium could not allocate the required memory (a critical message is
   * logged in that case).
   * @note Safe to call concurrently; no per-instance state is mutated.
   */
  std::optional<std::string> hashPassword(
      const std::string& password);  // Returns the encoded hash, or nothing
                                     // if hashing failed.

  /**
   * @brief Verifies @p password against a stored self-describing hash.
   * @details Selects the algorithm from the hash prefix: Argon2id
   * (`$argon2...`) or the legacy scrypt format (`$7$`). An unrecognized
   * prefix yields `false` rather than an exception. In everyday words: the
   * stored hash begins with a short label that says which recipe made it. We
   * read that label, run the matching check, and return true only for a real
   * match. Anything we do not understand is safely treated as a failed login,
   * not a crash.
   * @param[in] password Plaintext password to check.
   * @param[in] hash Stored hash string produced by hashPassword() or by the
   * legacy scheme.
   * @return `true` only if the password matches the hash; `false` on
   * mismatch, unknown algorithm, or malformed hash.
   */
  [[nodiscard]] bool verifyPassword(const std::string& password,
      const std::string& hash);  // [[nodiscard]] makes the compiler warn if a
                                 // caller ignores this true/false answer.
};
